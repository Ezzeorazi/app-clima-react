const RAIN_CODES = [1063,1150,1153,1168,1171,1180,1183,1186,1189,1192,1195,1198,1201,1240,1243,1246];
const SNOW_CODES = [1066,1069,1072,1114,1117,1204,1207,1210,1213,1216,1219,1222,1225,1237,1249,1252,1255,1258,1261,1264];
const STORM_CODES = [1087,1273,1276,1279,1282];
const FOG_CODES = [1030,1135,1147];

export function getWeatherTheme(conditionCode, isDay) {
  if (!conditionCode) return themes.default;
  if (conditionCode === 1000) return isDay ? themes.sunny_day : themes.clear_night;
  if (conditionCode === 1003) return isDay ? themes.cloudy : themes.cloudy_night;
  if ([1006, 1009].includes(conditionCode)) return isDay ? themes.cloudy : themes.cloudy_night;
  if (FOG_CODES.includes(conditionCode)) return themes.fog;
  if (RAIN_CODES.includes(conditionCode)) return themes.rain;
  if (SNOW_CODES.includes(conditionCode)) return themes.snow;
  if (STORM_CODES.includes(conditionCode)) return themes.storm;
  return isDay ? themes.cloudy : themes.cloudy_night;
}

export function glassCard(theme, extraSx = {}) {
  return {
    background: theme.glass,
    backdropFilter: 'blur(20px)',
    WebkitBackdropFilter: 'blur(20px)',
    border: `1px solid ${theme.glassBorder}`,
    borderRadius: '20px',
    boxShadow: theme.glassShadow,
    color: theme.text,
    ...extraSx,
  };
}
